-- tora-qual-lock 资格变更日志（Oracle 12c+）。表名改了的话，同时配置 tora.qual.log.table
-- Oracle 会把空字符串 '' 当成 NULL，所以 suffix、log_field、biz_id、remark 只能允许 NULL（其他数据库是 NOT NULL DEFAULT ''）。
-- 组合索引 idx_tora_qual_log_key 第一列 quota_name 非空，suffix 为 NULL 的行照样进索引。
CREATE TABLE tora_qual_log (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quota_name VARCHAR2(100 CHAR) NOT NULL,
  suffix VARCHAR2(100 CHAR) NULL,
  log_type VARCHAR2(10 CHAR) NOT NULL,
  log_field VARCHAR2(10 CHAR) NULL,
  amount NUMBER(19) DEFAULT 0 NOT NULL,
  total_before NUMBER(19) DEFAULT 0 NOT NULL,
  total_after NUMBER(19) DEFAULT 0 NOT NULL,
  used_before NUMBER(19) DEFAULT 0 NOT NULL,
  used_after NUMBER(19) DEFAULT 0 NOT NULL,
  expire_before TIMESTAMP(3) NULL,
  expire_after TIMESTAMP(3) NULL,
  biz_id VARCHAR2(64 CHAR) NULL,
  remark VARCHAR2(255 CHAR) NULL,
  created_at TIMESTAMP(3) NOT NULL
);
CREATE INDEX idx_tora_qual_log_key ON tora_qual_log (quota_name, suffix, created_at);
CREATE INDEX idx_tora_qual_log_biz ON tora_qual_log (biz_id);
CREATE INDEX idx_tora_qual_log_time ON tora_qual_log (created_at);
COMMENT ON TABLE tora_qual_log IS 'tora-qual-lock 资格变更日志';

