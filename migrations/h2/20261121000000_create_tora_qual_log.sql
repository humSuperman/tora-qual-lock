-- tora-qual-lock 资格变更日志（H2）。表名改了的话，同时配置 tora.qual.log.table
CREATE TABLE tora_qual_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quota_name VARCHAR(100) NOT NULL,
  suffix VARCHAR(100) DEFAULT '' NOT NULL,
  log_type VARCHAR(10) NOT NULL,
  log_field VARCHAR(10) DEFAULT '' NOT NULL,
  amount BIGINT DEFAULT 0 NOT NULL,
  total_before BIGINT DEFAULT 0 NOT NULL,
  total_after BIGINT DEFAULT 0 NOT NULL,
  used_before BIGINT DEFAULT 0 NOT NULL,
  used_after BIGINT DEFAULT 0 NOT NULL,
  expire_before TIMESTAMP(3) NULL,
  expire_after TIMESTAMP(3) NULL,
  biz_id VARCHAR(64) DEFAULT '' NOT NULL,
  remark VARCHAR(255) DEFAULT '' NOT NULL,
  created_at TIMESTAMP(3) NOT NULL
);
CREATE INDEX idx_tora_qual_log_key ON tora_qual_log (quota_name, suffix, created_at);
CREATE INDEX idx_tora_qual_log_biz ON tora_qual_log (biz_id);
CREATE INDEX idx_tora_qual_log_time ON tora_qual_log (created_at);

